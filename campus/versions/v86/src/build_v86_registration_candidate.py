OUT_GEOJSON = ROOT / 'data/BNBU_v86_REGISTRATION_QA_ONLY.geojson'
OUT_VIEWER = ROOT / 'viewer/BNBU_v86_T1_T3_OSM_Registration_Comparison.html'

PARENT_SHA = hashlib.sha256(PARENT.read_bytes()).hexdigest()
EXPECTED_PARENT_SHA = '242ade4c7cf25a4437e674b271ea451f9367449c23530ca95679b33749989848'
assert PARENT_SHA == EXPECTED_PARENT_SHA, PARENT_SHA
