OSM_SOURCE = 'https://u-map.haotian22.top/poi.json'
OSM_QUERY_SOURCE = 'https://github.com/HaoTian22/BNBU-Map/blob/main/Overpass.txt'
COORD_OFFSET = np.array([758940.0, 2474080.0])
TO_UTM = Transformer.from_crs('EPSG:4326', 'EPSG:32649', always_xy=True)
TO_WGS = Transformer.from_crs('EPSG:32649', 'EPSG:4326', always_xy=True)

# Exact component selection: all named T1/T2/T3 components plus bridge slabs 04/05.
TOKEN_RE = re.compile(r'(?<![A-Z0-9])T[123](?![0-9])')
BRIDGE_NODES = {
    'V52_LEVEL2_PEDESTRIAN_CONNECTION_04_CLOSED_SLAB_EXISTING_TOPOGRAPHY',
    'V52_LEVEL2_PEDESTRIAN_CONNECTION_05_CLOSED_SLAB_EXISTING_TOPOGRAPHY',
}
NODES = sorted(n for n in SCENE.graph.nodes_geometry if TOKEN_RE.search(n) or n in BRIDGE_NODES)
assert len(NODES) == 173, len(NODES)
FACE_COUNT = sum(len(SCENE.geometry[SCENE.graph[n][1]].faces) for n in NODES)
assert FACE_COUNT == 10700, FACE_COUNT

# Model bbox centres are computed from the main facade/sidewall source meshes.
model_centres = {}
for building in ('T1','T2','T3'):
    node = f'V40_MAIN_{building}_FACADE_AND_SIDEWALLS'
    assert node in SCENE.graph.nodes_geometry
    tf, key = SCENE.graph[node]
    mesh = SCENE.geometry[key].copy()
    mesh.apply_transform(tf)
    local_xy = mesh.bounds.mean(axis=0)[:2]
    model_centres[building] = local_xy + COORD_OFFSET

osm_centres = {}
for building, row in OSM.items():
    osm_centres[building] = np.array(TO_UTM.transform(row['lon'], row['lat']), dtype=float)

# Translation is the least-squares mean of the three same-frame bbox-centre deltas.
deltas = {b: osm_centres[b] - model_centres[b] for b in ('T1','T2','T3')}
SHIFT = np.mean(np.stack(list(deltas.values())), axis=0)
SHIFT3 = np.array([SHIFT[0], SHIFT[1], 0.0])
shift_matrix = np.eye(4)
shift_matrix[:3,3] = SHIFT3
residuals = {b: deltas[b] - SHIFT for b in ('T1','T2','T3')}
residual_norms = {b: float(np.linalg.norm(residuals[b])) for b in ('T1','T2','T3')}
RMS = float(np.sqrt(np.mean([v*v for v in residual_norms.values()])))
MAX_RESIDUAL = max(residual_norms.values())

# Helper: exact world-space mesh for a scene node, with optional rigid translation.
def world_mesh(node, shift=False):
    tf, key = SCENE.graph[node]
    g = SCENE.geometry[key].copy()
    g.apply_transform(tf)
    if shift:
        g.apply_translation(SHIFT3)
    return g

# Create a candidate-only GLB for loading as a separate display-only collection.
cand_scene = trimesh.Scene()
for node in NODES:
    tf, key = SCENE.graph[node]
    g = SCENE.geometry[key].copy()
    cand_scene.add_geometry(g, geom_name=f'CANDIDATE__{node}', node_name=f'CANDIDATE__{node}',
                            transform=shift_matrix @ tf)
cand_scene.export(OUT_CAND, file_type='glb')

# Create a comparison GLB with both unchanged baseline and shifted candidate collections.
pair_scene = trimesh.Scene()
for node in NODES:
    tf, key = SCENE.graph[node]
    g0 = SCENE.geometry[key].copy()
    g1 = SCENE.geometry[key].copy()
    pair_scene.add_geometry(g0, geom_name=f'BASELINE__{node}', node_name=f'BASELINE__{node}', transform=tf)
    pair_scene.add_geometry(g1, geom_name=f'CANDIDATE__{node}', node_name=f'CANDIDATE__{node}',
                            transform=shift_matrix @ tf)
pair_scene.export(OUT_PAIR, file_type='glb')

# Round-trip validation: original mesh topology/vertices unchanged; candidate differs only by translation.
reimport = trimesh.load(OUT_PAIR, force='scene', process=False)
assert len(reimport.graph.nodes_geometry) == 346
assert sum(len(g.faces) for g in reimport.geometry.values()) == FACE_COUNT * 2
roundtrip = {'baseline_meshes_checked': 0, 'candidate_meshes_checked': 0,
             'max_baseline_vertex_error_m': 0.0, 'max_candidate_translation_error_m': 0.0,
             'face_index_arrays_identical': True, 'vertex_count_identical': True}
for node in NODES:
    tf0, key0 = SCENE.graph[node]
    g0 = SCENE.geometry[key0]
    bn = f'BASELINE__{node}'
    cn = f'CANDIDATE__{node}'
    tbf, kbf = reimport.graph[bn]
    tcf, kcf = reimport.graph[cn]
    gb = reimport.geometry[kbf]
    gc = reimport.geometry[kcf]
    roundtrip['baseline_meshes_checked'] += 1
    roundtrip['candidate_meshes_checked'] += 1
    if len(gb.vertices) != len(g0.vertices) or len(gc.vertices) != len(g0.vertices):
        roundtrip['vertex_count_identical'] = False
    if not np.array_equal(gb.faces, g0.faces) or not np.array_equal(gc.faces, g0.faces):
        roundtrip['face_index_arrays_identical'] = False
    # Compare world-space triangles; GLB re-encoding may quantize at float32 precision.
    expected0 = g0.copy(); expected0.apply_transform(tf0)
    actual0 = gb.copy(); actual0.apply_transform(tbf)
    expected1 = expected0.copy(); expected1.apply_translation(SHIFT3)
    actual1 = gc.copy(); actual1.apply_transform(tcf)
    e0 = float(np.max(np.abs(actual0.vertices - expected0.vertices)))
    e1 = float(np.max(np.abs(actual1.vertices - expected1.vertices)))
    roundtrip['max_baseline_vertex_error_m'] = max(roundtrip['max_baseline_vertex_error_m'], e0)
    roundtrip['max_candidate_translation_error_m'] = max(roundtrip['max_candidate_translation_error_m'], e1)
assert roundtrip['face_index_arrays_identical'] and roundtrip['vertex_count_identical']
assert roundtrip['max_baseline_vertex_error_m'] < 2e-5
assert roundtrip['max_candidate_translation_error_m'] < 2e-5

# Component manifest and per-node invariants.
manifest=[]
for node in NODES:
    tf,key=SCENE.graph[node]
    g=SCENE.geometry[key]
    group = 'V52_04' if node in BRIDGE_NODES and '_04_' in node else 'V52_05' if node in BRIDGE_NODES else next(t for t in ('T1','T2','T3') if TOKEN_RE.search(node) and re.search(rf'(?<![A-Z0-9]){t}(?![0-9])',node))
    world=world_mesh(node)
    manifest.append({'node':node,'group':group,'vertices':len(g.vertices),'triangles':len(g.faces),
                     'baseline_world_bounds':world.bounds.round(8).tolist(),
                     'candidate_world_bounds':(world.bounds+np.array([SHIFT3,SHIFT3])).round(8).tolist(),
                     'source_local_vertices_sha256':hashlib.sha256(np.asarray(g.vertices,dtype='<f4').tobytes()).hexdigest(),
                     'source_face_indices_sha256':hashlib.sha256(np.asarray(g.faces,dtype='<u4').tobytes()).hexdigest(),
                     'scene_transform':tf.round(10).tolist(),
                     'candidate_transform':(shift_matrix@tf).round(10).tolist(),
                     'shape_change':False})
OUT_MANIFEST.write_text(json.dumps({'parent_sha256':PARENT_SHA,'candidate_translation_utm_m':SHIFT3.tolist(),
                                    'components':manifest},ensure_ascii=False,indent=2),'utf-8')

# Recheck four source-face endpoints on V52_04/05 before and after the candidate shift.
old_probes=json.loads(PROBES.read_text('utf-8'))
endpoint_rows=[]
# Cache world meshes and bounds once; exclude no physical surface except the endpoint's own bridge.
cache={n:world_mesh(n) for n in SCENE.graph.nodes_geometry}

def bbox_gap(bounds, point):
    lo,hi=bounds
    d=np.maximum(np.maximum(lo-point,point-hi),0.0)
    return float(np.linalg.norm(d))

def nearest_surfaces(point, own_bridge, shifted_state, limit=25.0, topn=5, include_selected=True):
    vals=[]
    for n,g0 in cache.items():
        if n==own_bridge: continue
        if not include_selected and n in NODES: continue
        # For candidate state, only the 173 selected components receive the same shift.
        if shifted_state and n in NODES:
            # Translation is a rigid shift; use the translated point against the original mesh.
            target=g0
            query=point-SHIFT3
        else:
            target=g0
            query=point
        if bbox_gap(target.bounds,query)>limit: continue
        try:
            near,dist,face=trimesh.proximity.closest_point_naive(target,query[None,:])
        except Exception:
            continue
        d=float(dist[0])
        if d>limit: continue
        fi=int(face[0])
        normal=target.face_normals[fi]
        q=near[0]
        # Candidate-state surface point must be shifted when its mesh belongs to the group.
        if shifted_state and n in NODES:
            q=q+SHIFT3
        vals.append({'node':n,'distance_3d_model_m':round(d,8),
                     'distance_xy_model_m':round(float(np.linalg.norm(q[:2]-point[:2])),8),
                     'source_face_index':fi,'nearest_point_xyz_model':q.round(8).tolist(),
                     'delta_z_model_m':round(float(q[2]-point[2]),8),
                     'face_normal':normal.round(8).tolist(),
                     'surface_class':('roof_or_soffit_facing' if normal[2]>.75 else 'vertical_or_sloped_surface')})
    vals.sort(key=lambda x:x['distance_3d_model_m'])
    return vals[:topn]

for p in old_probes:
    if p['bridge_node'] not in BRIDGE_NODES: continue
    point=np.asarray(p['xyz_local_model'],dtype=float)
    base=nearest_surfaces(point,p['bridge_node'],False)
    shifted_point=point+SHIFT3
    cand=nearest_surfaces(shifted_point,p['bridge_node'],True)
    base_external=nearest_surfaces(point,p['bridge_node'],False,include_selected=False)
    cand_external=nearest_surfaces(shifted_point,p['bridge_node'],True,include_selected=False)
    endpoint_rows.append({'id':p['id'],'bridge_node':p['bridge_node'],
                          'source_face_index':p['source_face_index'],
                          'source_face_normal_xyz':p['source_face_normal_xyz'],
                          'baseline_xyz_model':point.round(8).tolist(),
                          'candidate_xyz_model':shifted_point.round(8).tolist(),
                          'baseline_nearest_surfaces':base,
                          'candidate_nearest_surfaces':cand,
                          'baseline_nearest_unshifted_external_surfaces':base_external,
                          'candidate_nearest_unshifted_external_surfaces':cand_external,
                          'is_routable':False,'is_verified_connected':False,
                          'note':'Exact source-face re-probe in the candidate coordinate scenario; no access, door, walkway, or public route is certified.'})
assert len(endpoint_rows)==4
OUT_ENDPOINTS.write_text(json.dumps({'version':'v86','parent_sha256':PARENT_SHA,'candidate_shift_xy_m':SHIFT.tolist(),
                                     'endpoints':endpoint_rows,'all_routable':False},ensure_ascii=False,indent=2),'utf-8')

# QA-only GIS: model centres, Overpass bbox centres, residual vectors, candidate vectors.
features=[]
center_rows=[]; residual_rows=[]; shift_rows=[]
for b in ('T1','T2','T3'):
    model_xy=model_centres[b]
    osm_xy=osm_centres[b]
    cand_xy=model_xy+SHIFT
    mlon,mlat=TO_WGS.transform(float(model_xy[0]),float(model_xy[1]))
    clon,clat=TO_WGS.transform(float(cand_xy[0]),float(cand_xy[1]))
    olon,olat=OSM[b]['lon'],OSM[b]['lat']
    common={'building':b,'osm_way_id':OSM[b]['way_id'],'osm_timestamp':OSM_TIMESTAMP,
            'source_type':'Overpass out center (bounding-box center)','surveyed':False,
            'is_surveyed':0,'display_only':True,'is_routable':0}
    for state,xy,lon,lat in [('osm_bbox_center',osm_xy,olon,olat),('model_baseline',model_xy,mlon,mlat),('model_candidate',cand_xy,clon,clat)]:
        props={**common,'state':state,'utm_x':float(xy[0]),'utm_y':float(xy[1]),'longitude':float(lon),'latitude':float(lat)}
        geom=Point(float(lon),float(lat))
        center_rows.append({**props,'geometry':geom})
        features.append({'type':'Feature','geometry':mapping(geom),'properties':props})
    # Baseline and candidate residual lines end at the OSM bbox centre.
    for state,xy,lon,lat in [('baseline_to_osm',model_xy,mlon,mlat),('candidate_to_osm',cand_xy,clon,clat)]:
        dv=osm_xy-xy
        dist=float(np.linalg.norm(dv))
        geom=LineString([(float(lon),float(lat)),(float(olon),float(olat))])
        props={**common,'state':state,'dx_to_osm_m':float(dv[0]),'dy_to_osm_m':float(dv[1]),
               'distance_m':dist,'geometry_kind':'bbox-centre residual, not surveyed control'}
        residual_rows.append({**props,'geometry':geom})
        features.append({'type':'Feature','geometry':mapping(geom),'properties':props})
    # Candidate translation vector from baseline centre to translated centre.
    geom=LineString([(float(mlon),float(mlat)),(float(clon),float(clat))])
    props={**common,'state':'candidate_translation','dx_m':float(SHIFT[0]),'dy_m':float(SHIFT[1]),
           'distance_m':float(np.linalg.norm(SHIFT)),'geometry_kind':'display-only rigid translation'}
    shift_rows.append({**props,'geometry':geom})
    features.append({'type':'Feature','geometry':mapping(geom),'properties':props})

# Write a standalone QA GeoPackage; never append to or overwrite the physical master GPKG.
if OUT_GPKG.exists(): OUT_GPKG.unlink()
for layer,rows in [('registration_centres',center_rows),('registration_residuals',residual_rows),('candidate_shift_vectors',shift_rows)]:
    gdf=gpd.GeoDataFrame(rows,geometry='geometry',crs='EPSG:4326')
    gdf.to_file(OUT_GPKG,layer=layer,driver='GPKG',mode='w' if layer=='registration_centres' else 'a')
OUT_GEOJSON.write_text(json.dumps({'type':'FeatureCollection','name':'BNBU_v86_REGISTRATION_QA_ONLY',
                                   'crs':{'type':'name','properties':{'name':'urn:ogc:def:crs:OGC:1.3:CRS84'}},
                                   'features':features},ensure_ascii=False,indent=2),'utf-8')

