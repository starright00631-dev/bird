#!/usr/bin/env python3
"""Build a reversible, display-only T1-T3 / V52-04/05 registration candidate.

Parent is the v84 GLB carried by v85. The active master and physical GIS are never
modified. The candidate is the least-squares XY translation from three Overpass
OSM way bounding-box centres to three model bounding-box centres. OSM centres are
not surveyed controls, so the output is strictly an alternative display layer.
"""
from pathlib import Path
import hashlib, json, re, math
import numpy as np
import trimesh
import geopandas as gpd
from shapely.geometry import Point, LineString, mapping
from pyproj import Transformer

ROOT = Path(__file__).resolve().parents[1]
PARENT = ROOT / 'model/BNBU_v84_FULL_EDITABLE.glb'
PROBES = ROOT / 'qa/v83_v52_probe.json'
OUT_CAND = ROOT / 'model/BNBU_v86_T1_T3_V52_04_05_TRANSLATED_DISPLAY_ONLY.glb'
OUT_PAIR = ROOT / 'model/BNBU_v86_T1_T3_V52_04_05_BASELINE_AND_CANDIDATE.glb'
OUT_AUDIT = ROOT / 'qa/v86_registration_audit.json'
